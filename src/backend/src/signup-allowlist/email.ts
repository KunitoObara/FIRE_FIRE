/**
 * 許可リストの照合に使うメールアドレスの正規化(docs/auth-login-requirements.md 3.10)。
 *
 * 承認する側は手で入力するため、`Taro@Example.com` のような表記や、コピー時に紛れ込んだ
 * 空白で弾かれる事故が起きる。**招待した本人が登録できないのは、この機能の失敗のしかたとして
 * 最も避けたいもの**なので、比べる前に両側を同じ形に揃える。
 */

/**
 * 小文字化と前後の空白の除去だけを行う。
 *
 * **これ以上のあいまい一致はしない。** ドット除去やプラス以降の切り捨て
 * (`taro+fire@gmail.com` → `taro@gmail.com`)といったプロバイダ固有の正規化は、
 * 事業者ごとに規則が違い、正しく実装しても「別人のアドレスを同一とみなす」方向に倒れうる。
 * 許可リストは登録できる人を決めるものなので、広がる方向の誤りは踏めない。
 *
 * 小文字化に `toLowerCase` を使うのは、ロケール依存の変換を避けるため
 * (`toLocaleLowerCase` はトルコ語ロケールで `I` を `ı` に変える)。
 */
export const normalizeEmail = (email: string): string => email.trim().toLowerCase();
